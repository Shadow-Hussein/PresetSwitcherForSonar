using System.Diagnostics;
using System.Globalization;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Win32;
using SonarPresetSwitcher.Models;

namespace SonarPresetSwitcher.Services;

/// <summary>
/// Adds a gain to Sonar's microphone, chosen by which physical microphone Sonar is reading from.
///
/// Sonar cannot do this itself. Its mic config has no gain field, and its mic volume is validated to
/// 0-1 (<c>RedirectionEngine.ValidateLinearGain</c> in <c>SoundStage.Services.dll</c>), so the only
/// Sonar levers above 100% are the Volume Stabilizer and the EQ. The gain is an Equalizer APO
/// <c>Preamp</c> instead — uncapped, and applied by Windows' own audio engine, so nothing has to keep
/// running for the gain itself.
///
/// <b>The gain is always written for Sonar's virtual microphone, never for the physical one.</b> Sonar
/// reads the physical mic RAW, which bypasses every APO, so a preamp there is never heard through
/// Sonar; on "SteelSeries Sonar - Microphone" it lands after Sonar's processing and every app recording
/// through Sonar gets it. That is also the only endpoint Equalizer APO has to be installed on.
///
/// The rules, though, are keyed on the <b>physical</b> microphone — "this much while Sonar is using
/// that mic" — because a quiet headset mic and a hot desk mic want different amounts. That makes this a
/// fourth small Sonar poller, the capture-side twin of <see cref="ChannelBoostService"/>: it watches
/// the <c>mic</c> entry of <c>/classicRedirections</c> and rewrites one file when the answer changes.
/// It is separate from that service because that one reduces redirections to Game and Media, follows
/// the Monitoring mix in streamer mode, and edits Sonar presets — none of which applies here.
///
/// The app owns a single file, <see cref="FileName"/>, in Equalizer APO's config folder, written only
/// when its content would actually change, and makes sure <c>config.txt</c> includes it.
/// <c>config.txt</c> is not ours — on at least one setup another tool regenerates it wholesale — so it
/// is only ever appended to, and the check is repeated on every flush, which is what puts the lines
/// back after such a rewrite.
///
/// The include is written as a pair, <c>Device: all</c> then <c>Include:</c>. Without the first line
/// the include sits under whichever selector <c>config.txt</c> ended on, and Equalizer APO skips every
/// command — includes too — while that selector does not match, so the file was never even opened.
/// </summary>
public sealed partial class MicGainService : IDisposable
{
    public const string FileName = "SonarPresetSwitcher.txt";

    /// <summary>Where Equalizer APO can be downloaded, for the setup guide's first step.</summary>
    public const string DownloadUrl = "https://sourceforge.net/projects/equalizerapo/";

    private const string RegistryPath = @"SOFTWARE\EqualizerAPO";
    private const string CaptureEndpointsPath =
        @"SOFTWARE\Microsoft\Windows\CurrentVersion\MMDevices\Audio\Capture";

    /// <summary>PKEY_AudioEndpoint_Disable_SysFx, as the value name it has under FxProperties.</summary>
    private const string DisableSysFxValue = "{1da5d803-d492-4edd-8c23-e0c0ffee7f0e},5";

    /// <summary>The <c>role</c> <c>/audioDevices</c> gives Sonar's microphone endpoint.</summary>
    private const string SonarMicRole = "chatCapture";

    private const string Header =
        "# Generated by Sonar Preset Switcher - microphone gain. Edit it in the app, not here.";

    private static readonly TimeSpan PollInterval = TimeSpan.FromSeconds(5);
    private static readonly TimeSpan ReconnectInterval = TimeSpan.FromSeconds(10);
    private static readonly UTF8Encoding Utf8NoBom = new(encoderShouldEmitUTF8Identifier: false);

    private readonly SonarClient _client;
    private readonly CancellationTokenSource _cts = new();
    private readonly Lock _gate = new();

    /// <summary>
    /// An immutable copy of the rules, taken on the UI thread in <see cref="UpdateSettings"/>. The
    /// rule list itself belongs to that thread, and both the loop and a queued flush read this instead.
    /// </summary>
    private volatile Snapshot _rules = new(false, []);

    private volatile string? _inputId;
    private volatile string? _outputId;

    private Task? _loop;
    private bool _reachable;

    /// <summary>Latch, so a failure that repeats on every flush is logged once. Guarded by the gate.</summary>
    private string? _lastProblem;

    public MicGainService(SonarClient client, AppSettings settings)
    {
        _client = client;
        _rules = Snapshot.Of(settings);
    }

    /// <summary>Human-readable lines for the activity log.</summary>
    public event Action<string>? Activity;

    /// <summary>Raised when <see cref="SonarInputId"/> or <see cref="SonarOutputId"/> has changed.</summary>
    public event Action? SonarMicChanged;

    /// <summary>
    /// MMDevice id of the physical microphone Sonar is reading from. Null means <i>unknown</i> — Sonar
    /// has not been reached — which is not the same as "" (reached, and no microphone is set).
    /// </summary>
    public string? SonarInputId => _inputId;

    /// <summary>MMDevice id of Sonar's own virtual microphone, or null until Sonar has reported it.</summary>
    public string? SonarOutputId => _outputId;

    public void Start() => _loop ??= Task.Run(() => LoopAsync(_cts.Token));

    /// <summary>Called on the UI thread whenever a rule or the feature toggle changes.</summary>
    public void UpdateSettings(AppSettings settings)
    {
        _rules = Snapshot.Of(settings);
        Task.Run(Flush);
    }

    /// <summary>
    /// One read of Sonar's microphone state, outside the loop's schedule. The view model calls it on a
    /// refresh so the "in use" dot and the default device for a new row are right before any rule
    /// exists — the loop itself asks Sonar nothing until there is one.
    /// </summary>
    public async Task RefreshSonarAsync(CancellationToken ct = default)
    {
        await ReadSonarAsync(ct).ConfigureAwait(false);
        Flush();
    }

    private async Task LoopAsync(CancellationToken ct)
    {
        // Before any Sonar call: this is what takes a gain back out when the feature was switched off
        // while the app was closed, and what restores the include after another tool rewrote config.txt.
        Flush();

        while (!ct.IsCancellationRequested)
        {
            try
            {
                // A user who never adds a rule should not be paying a GET every five seconds for it.
                if (_rules.Items.Count > 0)
                {
                    await ReadSonarAsync(ct).ConfigureAwait(false);
                    Flush();
                }
            }
            catch (OperationCanceledException)
            {
                return;
            }
            catch (Exception ex)
            {
                Debug.WriteLine($"Mic gain tick failed: {ex}");
            }

            try
            {
                await Task.Delay(_reachable ? PollInterval : ReconnectInterval, ct).ConfigureAwait(false);
            }
            catch (OperationCanceledException)
            {
                return;
            }
        }
    }

    private async Task ReadSonarAsync(CancellationToken ct)
    {
        var redirections = await _client.GetClassicRedirectionsAsync(ct).ConfigureAwait(false);

        string? input = null;
        var output = _outputId;

        if (redirections is null)
        {
            _reachable = false;
        }
        else
        {
            _reachable = true;

            // "" when Sonar has no microphone set: known, and matching no rule.
            input = redirections
                .FirstOrDefault(r => string.Equals(r.Id, SonarRedirection.MicChannel, StringComparison.OrdinalIgnoreCase))?
                .DeviceId ?? "";

            // Re-read every tick rather than once: GG hands its virtual endpoints fresh ids whenever it
            // rebuilds its driver. A failed read keeps the last answer, which is still the best guess.
            var devices = await _client.GetAudioDevicesAsync(ct).ConfigureAwait(false);
            if (devices is not null)
                output = FindSonarMicrophone(devices) ?? output;
        }

        if (string.Equals(input, _inputId, StringComparison.OrdinalIgnoreCase) &&
            string.Equals(output, _outputId, StringComparison.OrdinalIgnoreCase))
            return;

        _inputId = input;
        _outputId = output;
        SonarMicChanged?.Invoke();
    }

    /// <summary>
    /// Sonar's microphone among its virtual capture endpoints: the one in the <c>chatCapture</c> role.
    /// Any virtual capture endpoint is the fallback, for a GG build that reports roles differently.
    /// </summary>
    private static string? FindSonarMicrophone(IReadOnlyList<SonarAudioDevice> devices)
    {
        var virtualMics = devices
            .Where(d => d.IsVad && string.Equals(d.DataFlow, "capture", StringComparison.OrdinalIgnoreCase))
            .ToList();

        var mic = virtualMics.FirstOrDefault(d =>
                      string.Equals(d.Role, SonarMicRole, StringComparison.OrdinalIgnoreCase))
                  ?? virtualMics.FirstOrDefault();

        return string.IsNullOrEmpty(mic?.Id) ? null : mic.Id;
    }

    /// <summary>
    /// Brings <see cref="FileName"/> in line with the rules and Sonar's current microphone. Cheap when
    /// nothing changed — two small file reads — so the loop calls it every tick.
    /// </summary>
    private void Flush()
    {
        lock (_gate)
        {
            var rules = _rules;
            var live = rules.Enabled
                ? rules.Items.Where(r => r.Enabled && r.Db > 0).ToList()
                : [];

            var directory = ConfigDirectory;
            if (directory is null)
            {
                // Silent unless the user is actually asking for a gain: most machines have no
                // Equalizer APO, and that is not news to someone who never ticked the box.
                if (live.Count > 0)
                    Report("Microphone gain needs Equalizer APO, which is not installed.");

                return;
            }

            try
            {
                var path = Path.Combine(directory, FileName);
                var exists = File.Exists(path);

                // Never used, never created: an untouched feature leaves no trace in someone else's folder.
                if (live.Count == 0 && !exists)
                    return;

                var content = Header + "\r\n";
                var message = "Microphone gain removed.";

                if (live.Count > 0)
                {
                    EnsureIncluded(directory);

                    var input = _inputId;
                    var outputGuid = EndpointGuid(_outputId);

                    // Unknown is not "no rule matches". With Sonar unreachable there is no evidence the
                    // gain is unwanted, so whatever is on disk stays — the same reasoning that makes
                    // the boost service hold through an unreadable routing table.
                    if (input is null || outputGuid is null)
                        return;

                    var active = live.FirstOrDefault(r =>
                        string.Equals(r.DeviceId, input, StringComparison.OrdinalIgnoreCase));

                    if (active is null)
                    {
                        message = "Microphone gain removed — Sonar's current microphone has no rule.";
                    }
                    else
                    {
                        var value = active.Db.ToString("0.#", CultureInfo.InvariantCulture);

                        content +=
                            $"\r\n# +{value} dB while Sonar's microphone input is {Ascii(active.Name)}\r\n" +
                            $"Device: {outputGuid}\r\n" +
                            $"Preamp: {value} dB\r\n";

                        message = $"Microphone gain +{value} dB — Sonar is using {active.Name}.";
                    }
                }

                if (exists && File.ReadAllText(path) == content)
                {
                    _lastProblem = null;
                    return;
                }

                // Same shape as SettingsStore: a sibling temp file, so an interrupted write cannot leave
                // Equalizer APO parsing half a config.
                var temp = path + ".tmp";
                File.WriteAllText(temp, content, Utf8NoBom);
                File.Move(temp, path, overwrite: true);

                _lastProblem = null;
                Activity?.Invoke(message);
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                Report($"Could not write the microphone gain to Equalizer APO's config: {ex.Message}");
            }
        }
    }

    /// <summary>
    /// Adds the include pair to <c>config.txt</c> when it is not already there. Append-only apart from
    /// repairing our own earlier line: the rest of that file is somebody else's, in an encoding we have
    /// no business re-writing.
    /// </summary>
    private void EnsureIncluded(string directory)
    {
        var config = Path.Combine(directory, "config.txt");
        var bytes = File.Exists(config) ? File.ReadAllBytes(config) : [];

        // A UTF-16 file would take appended single-byte text as garbage, corrupting a working config.
        if (bytes.Length >= 2 && ((bytes[0] == 0xFF && bytes[1] == 0xFE) || (bytes[0] == 0xFE && bytes[1] == 0xFF)))
        {
            Report($"Equalizer APO's config.txt is UTF-16, so the include was not added. Add " +
                   $"\"Device: all\" and \"Include: {FileName}\" to it by hand.");
            return;
        }

        // Latin-1 maps every byte to one char and back, so the rest of the file survives the repair
        // below byte for byte whatever encoding it is really in.
        var existing = Encoding.Latin1.GetString(bytes);
        if (ScopedInclude().IsMatch(existing))
            return;

        // A bare include left by an earlier build. It is our own line, so it is ours to fix in place.
        if (IncludeLine().IsMatch(existing))
        {
            var repaired = IncludeLine().Replace(existing, m => "Device: all\r\n" + m.Value);

            var temp = config + ".tmp";
            File.WriteAllBytes(temp, Encoding.Latin1.GetBytes(repaired));
            File.Move(temp, config, overwrite: true);

            Activity?.Invoke($"Repaired the \"Include: {FileName}\" line in Equalizer APO's config.txt.");
            return;
        }

        var separator = existing.Length == 0 || existing.EndsWith('\n') ? "" : "\r\n";

        File.AppendAllText(
            config,
            $"{separator}\r\n# ===== Sonar Preset Switcher: microphone gain, after everything above\r\n" +
            $"Device: all\r\nInclude: {FileName}\r\n",
            Utf8NoBom);

        Activity?.Invoke($"Added \"Include: {FileName}\" to Equalizer APO's config.txt.");
    }

    private void Report(string problem)
    {
        if (_lastProblem == problem)
            return;

        _lastProblem = problem;
        Activity?.Invoke(problem);
    }

    // ---- Equalizer APO's own state, all read-only ------------------------------------------------

    /// <summary>
    /// Equalizer APO's config folder, or null when it is not installed.
    ///
    /// Read from the 64-bit registry view explicitly: the release build is win-x86, and the default
    /// view would redirect to WOW6432Node, where Equalizer APO writes nothing.
    /// </summary>
    public static string? ConfigDirectory =>
        ReadInstallValue("ConfigPath") is { } path && Directory.Exists(path) ? path : null;

    public bool IsInstalled => ConfigDirectory is not null;

    /// <summary>
    /// Equalizer APO's own Device Selector, or null when it cannot be found. Installing the APO on an
    /// endpoint is its job and stays its job: it rewrites protected audio keys under HKLM, keeps a
    /// backup of what was there, and asks for the reboot — none of which this app should imitate. The
    /// setup guide launches it instead.
    /// </summary>
    public static string? DeviceSelectorPath
    {
        get
        {
            if (ReadInstallValue("InstallPath") is not { } directory)
                return null;

            var path = Path.Combine(directory, "DeviceSelector.exe");
            return File.Exists(path) ? path : null;
        }
    }

    private static string? ReadInstallValue(string name)
    {
        try
        {
            using var hklm = RegistryKey.OpenBaseKey(RegistryHive.LocalMachine, RegistryView.Registry64);
            using var key = hklm.OpenSubKey(RegistryPath);
            return key?.GetValue(name) as string;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or
                                       System.Security.SecurityException)
        {
            return null;
        }
    }

    /// <summary>
    /// Whether Equalizer APO is installed on this endpoint — it is opt-in per device, through its own
    /// Device Selector.
    /// </summary>
    public bool IsInstalledOn(string? deviceId)
    {
        var guid = EndpointGuid(deviceId);
        if (guid is null)
            return false;

        try
        {
            using var hklm = RegistryKey.OpenBaseKey(RegistryHive.LocalMachine, RegistryView.Registry64);
            using var key = hklm.OpenSubKey($@"{RegistryPath}\Child APOs\{guid}");
            return key is not null;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or
                                       System.Security.SecurityException)
        {
            return false;
        }
    }

    /// <summary>
    /// Whether Windows has audio enhancements switched off for this endpoint — "Audio enhancements:
    /// Off" in Settings, <c>PKEY_AudioEndpoint_Disable_SysFx</c> underneath. With it off Windows loads
    /// no APO on the endpoint at all, so Equalizer APO is installed, the config is correct, and the
    /// gain still does nothing. Nothing in Equalizer APO's own registry key shows it.
    ///
    /// Read only. It is an HKLM value and the user's own Windows setting; the guide says how to turn
    /// it back on rather than this app doing it.
    /// </summary>
    public bool EnhancementsDisabledOn(string? deviceId)
    {
        var guid = EndpointGuid(deviceId);
        if (guid is null)
            return false;

        try
        {
            using var hklm = RegistryKey.OpenBaseKey(RegistryHive.LocalMachine, RegistryView.Registry64);
            using var key = hklm.OpenSubKey($@"{CaptureEndpointsPath}\{guid}\FxProperties");

            return key?.GetValue(DisableSysFxValue) is int disabled && disabled != 0;
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or
                                       System.Security.SecurityException)
        {
            return false;
        }
    }

    /// <summary>Whether a gain written for this endpoint can actually reach it.</summary>
    public MicGainReadiness ReadinessOf(string? deviceId) =>
        !IsInstalledOn(deviceId) ? MicGainReadiness.NotInstalled
        : EnhancementsDisabledOn(deviceId) ? MicGainReadiness.EnhancementsOff
        : MicGainReadiness.Ready;

    /// <summary>
    /// The endpoint GUID out of an MMDevice id (<c>{0.0.1.00000000}.{guid}</c>), braces included and
    /// lower-cased, which is the form Equalizer APO uses for both its registry keys and its
    /// <c>Device:</c> selector. Parsed rather than sliced so nothing but a GUID can reach the config.
    /// </summary>
    internal static string? EndpointGuid(string? deviceId)
    {
        if (string.IsNullOrEmpty(deviceId))
            return null;

        var start = deviceId.LastIndexOf('{');
        var end = deviceId.LastIndexOf('}');
        if (start < 0 || end < start)
            return null;

        return Guid.TryParseExact(deviceId[start..(end + 1)], "B", out var guid)
            ? guid.ToString("B")
            : null;
    }

    /// <summary>Device names carry things like "®"; the comment is not worth an encoding question.</summary>
    private static string Ascii(string text) =>
        new(text.Where(c => c is >= ' ' and <= '~').ToArray());

    [GeneratedRegex(@"^[ \t]*Include[ \t]*:[ \t]*SonarPresetSwitcher\.txt[ \t]*\r?$",
        RegexOptions.IgnoreCase | RegexOptions.Multiline | RegexOptions.CultureInvariant)]
    private static partial Regex IncludeLine();

    /// <summary>
    /// The include with <c>Device: all</c> directly above it — the only form that works. Equalizer APO
    /// skips every command, <c>Include</c> among them, while the selector in force does not match the
    /// endpoint being processed, and <c>config.txt</c> ends on some other device's selector.
    /// </summary>
    [GeneratedRegex(
        @"^[ \t]*Device[ \t]*:[ \t]*all[ \t]*\r?\n[ \t]*Include[ \t]*:[ \t]*SonarPresetSwitcher\.txt[ \t]*\r?$",
        RegexOptions.IgnoreCase | RegexOptions.Multiline | RegexOptions.CultureInvariant)]
    private static partial Regex ScopedInclude();

    public void Dispose()
    {
        _cts.Cancel();
        _cts.Dispose();
    }

    private sealed record Rule(string DeviceId, string Name, bool Enabled, double Db);

    private sealed record Snapshot(bool Enabled, IReadOnlyList<Rule> Items)
    {
        public static Snapshot Of(AppSettings settings) => new(
            settings.ApplyMicGain,
            settings.MicGains
                .Select(r => new Rule(
                    r.DeviceId, AudioDevice.CleanName(r.DeviceName), r.Enabled, MicGainRule.Clamp(r.GainDb)))
                .ToList());
    }
}

/// <summary>Whether a gain written for an endpoint can actually reach it.</summary>
public enum MicGainReadiness
{
    Ready,

    /// <summary>Equalizer APO is not installed on this endpoint.</summary>
    NotInstalled,

    /// <summary>Installed, but Windows has audio enhancements off for the endpoint, bypassing it.</summary>
    EnhancementsOff,
}
